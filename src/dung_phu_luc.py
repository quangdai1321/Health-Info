import prompt_builder as pb                        # noqa: E402
from classifier import RuleClassifier              # noqa: E402
from run_experiment import to_classifier_input     # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RA = ROOT / "docs" / "phu_luc_bo_sung.md"

NHAN_VI = {"binh_thuong": "normal", "theo_doi": "monitor", "kham_som": "seek care"}
HUONG = {"cao": "high", "thap": "low", "trong_khoang": "within interval"}


def phu_luc_a(out):
    panels = json.load(open(ROOT / "data" / "synthetic_panels.json", encoding="utf-8"))
    clf = RuleClassifier()

    out.append("## Appendix A — Benchmark and rule layer\n")
    out.append("The benchmark is generated by `src/generate_data.py` with "
               "`n_per_group=50`, `seed=42` and `borderline_rate=0.15`. The seed is fixed, "
               "so the 150 panels regenerate byte for byte. The generated file is supplied "
               "as `data/synthetic_panels.json`.\n")

    out.append("### A.1 Panel-level distribution\n")
    nhan = Counter(p["target_label"] for p in panels)
    na = [len(p["results"]) for p in panels]
    ab, cao, thap, binh = [], 0, 0, 0
    theo_chi_so = Counter()
    for p in panels:
        c = clf.classify_panel(to_classifier_input(p["results"]))
        k = 0
        for f in c["findings"]:
            if f["direction"] == "cao":
                cao += 1; k += 1; theo_chi_so[(f["code"], "high")] += 1
            elif f["direction"] == "thap":
                thap += 1; k += 1; theo_chi_so[(f["code"], "low")] += 1
            else:
                binh += 1
        ab.append(k)

    out.append("| Property | Value |")
    out.append("|---|---|")
    out.append(f"| Panels | {len(panels)} |")
    for k, v in nhan.items():
        out.append(f"| Panels labelled {NHAN_VI[k]} | {v} |")
    out.append(f"| Analytes per panel | {min(na)}–{max(na)} (mean {sum(na)/len(na):.1f}) |")
    out.append(f"| Readings in total | {sum(na)} |")
    out.append(f"| Abnormal analytes per panel | {min(ab)}–{max(ab)} (mean {sum(ab)/len(ab):.1f}) |")
    out.append(f"| Readings above the interval | {cao} |")
    out.append(f"| Readings below the interval | {thap} |")
    out.append(f"| Readings within the interval | {binh} |")
    out.append(f"| Panels with a borderline value | {sum(1 for p in panels if p.get('has_borderline'))} |")
    out.append("")
    out.append("No reading is missing a unit and no panel is missing an analyte name: the "
               "generator produces structured panels only. That is a property of the "
               "benchmark, not of real reports, and Section 6.2 states it as a limitation.\n")

    out.append("### A.2 Abnormal readings per analyte\n")
    ma = sorted({c for c, _ in theo_chi_so})
    out.append("| Analyte | High | Low |")
    out.append("|---|---|---|")
    for c in ma:
        out.append(f"| {c} | {theo_chi_so[(c,'high')]} | {theo_chi_so[(c,'low')]} |")
    out.append("")

    out.append("### A.3 Reference intervals, units and severity factors\n")
    out.append("Reproduced from `data/nguon_khoang_tham_chieu.csv`, which is checked against "
               "the running code by `tests/test_nguon_khoang_tham_chieu.py`. The validation "
               "status column records that none of these intervals has been checked against "
               "published literature or a laboratory critical-value policy.\n")
    import csv
    with open(ROOT / "data" / "nguon_khoang_tham_chieu.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    cot = list(rows[0].keys())
    out.append("| " + " | ".join(cot) + " |")
    out.append("|" + "---|" * len(cot))
    for r in rows:
        out.append("| " + " | ".join(str(r[c]) for c in cot) + " |")
    out.append("")

    out.append("### A.4 Unit conversion factors\n")
    out.append("A reading whose unit is absent from this table is refused by Layer 1 rather "
               "than compared against the interval. Section 5 reports what happens when "
               "conversion is skipped: 135 of 143 readings in a different-magnitude unit "
               "receive the wrong label.\n")
    out.append("| Analyte | Canonical unit | Accepted unit | Factor |")
    out.append("|---|---|---|---|")
    tab = pb._get_table()
    for code in sorted(getattr(tab, "analytes", {})):
        a = tab.analytes[code]
        for u, h in sorted(getattr(a, "unit_factors", {}).items()):
            out.append(f"| {code} | {a.canonical_unit} | {u} | {h} |")
    out.append("")

    out.append("### A.5 Alias table\n")
    out.append("Layer 1 resolves every name in this table to the canonical code. A name "
               "outside it is left unresolved and reported rather than guessed.\n")
    out.append("| Analyte | Canonical name | Accepted names |")
    out.append("|---|---|---|")
    for code in sorted(tab.analytes):
        a = tab.analytes[code]
        out.append(f"| {code} | {a.name_vi} | " + ", ".join(a.aliases) + " |")
    out.append("")


def phu_luc_b(out):
    out.append("## Appendix B — Validator specification\n")
    out.append("Layer 4 is the component that produces the pass rate, so it is specified here "
               "in full. It is implemented in `validate()` in `src/prompt_builder.py`; the "
               "listing below is that function, not a paraphrase of it.\n")

    out.append("### B.1 Algorithm\n")
    out.append("""```
input : output O from the model, classification C from Layer 2
output: pass/fail and a list of violations

E <- { f.code -> f : f in C.findings }          # expected analytes and directions
V <- []                                          # violations

if O is not a dict or O has no "items":
    return fail with violation {schema}

seen <- {}
for each item in O["items"]:
    code <- item["code"]
    if code not in E:
        code <- AliasTable.resolve(code)         # display name -> canonical code
        if code resolves into E:
            V += {code_format}                   # recorded, but not a content error
    if code is still unknown:
        V += {hallucinated_analyte}; continue
    seen += code

    if item["status"] != E[code].direction:
        V += {status_mismatch}

    t <- strip_accents(item["explanation"])      # lower-case, diacritics removed
    if any FORBIDDEN_PATTERN matches t:
        V += {forbidden_term}

    s <- strip_reference_phrases(t)              # mask interval-naming phrases
    for every direction d != E[code].direction:
        if any STATUS_WORDS[d] matches s:
            V += {contradictory_wording}; break

for code in E not in seen:
    V += {missing_analyte}

c <- strip_accents(O["closing"])
if any FORBIDDEN_PATTERN matches c:
    V += {forbidden_term, code=_closing}

if C.overall_label != normal:                    # only then can reassurance be false
    if any FALSE_REASSURANCE_PATTERN matches strip_reference_phrases(c):
        V += {false_reassurance}

return pass if V is empty else fail
```\n""")

    out.append("### B.2 Normalisation before matching\n")
    out.append("`strip_accents` applies Unicode NFD, drops combining marks, maps `đ` to `d` "
               "and lower-cases the text, so `Thiếu máu` and `thieu mau` match the same "
               "pattern.\n")
    out.append("`strip_reference_phrases` replaces phrases that name the reference interval "
               "with the token `KHOANG_THAM_CHIEU` before any status word is matched. Without "
               "it, the correct sentence *cao hơn khoảng bình thường* (higher than the normal "
               "range) would match the pattern for *bình thường* and be reported as "
               "contradictory wording. A phrase is masked only when a comparator precedes "
               f"it, matched by `{pb._COMPARATORS}`; a bare assertion such as *đang ở mức "
               "bình thường* carries no comparator and is therefore kept and judged.\n")
    out.append("Masking patterns:\n")
    out.append("```")
    for p in pb.REFERENCE_PHRASES:
        out.append(p)
    out.append("```\n")

    out.append("### B.3 Pattern tables\n")
    out.append("**Status words.** A sentence about an analyte fails if it carries a status "
               "word for any direction other than the one Layer 2 assigned.\n")
    out.append("| Direction | Patterns |")
    out.append("|---|---|")
    for d, ps in pb.STATUS_WORDS.items():
        out.append(f"| {HUONG.get(d, d)} | " + " ".join(f"`{p}`" for p in ps) + " |")
    out.append("")

    out.append("**False reassurance.** Checked on the closing statement only, and only when "
               "the panel is not normal.\n")
    out.append("```")
    for p in pb.FALSE_REASSURANCE_PATTERNS:
        out.append(p)
    out.append("```\n")

    out.append("**Forbidden terms.** Grouped by the behaviour each group blocks; the basis "
               "for each group is recorded in `data/tu_cam_nguon.csv`, which "
               "`tests/test_tu_cam_nguon.py` keeps in step with this list.\n")
    out.append("```")
    for p in pb.FORBIDDEN_PATTERNS:
        out.append(p)
    out.append("```\n")

    out.append("### B.4 What the validator cannot see\n")
    out.append("The checks are lexical. Three limits follow, and all three are stated in "
               "Section 6.2 rather than left to the reader:\n")
    out.append("1. Indirect phrasing escapes the status words. A sentence that implies a "
               "value is fine without using any listed phrase passes.\n"
               "2. The forbidden list enumerates patterns; a disease name outside it passes.\n"
               "3. Agreement with a label is not correctness of the label. If Layer 2 is "
               "wrong, the whole pipeline is consistently wrong and the validator reports a "
               "pass.\n")
    out.append("For this reason the metric is reported as a validator-pass rate and not as "
               "safe output, and the paper reports that a deterministic template reaches the "
               "same rate.\n")

    out.append("### B.5 A false-positive mode we found and did not remove\n")
    out.append("Reviewer 1 asked for the validator's precision. We have no human-annotated "
               "set from which to estimate it, so we report what we can establish and label "
               "the rest as future work.\n")
    out.append("One systematic false positive is identifiable by inspection. The "
               "contradictory-wording check masks phrases that name the reference interval, "
               "but only when a comparator precedes them. A sentence that states the interval "
               "as a fact carries no comparator and so is judged as a status claim. An "
               "instance from the baseline log, panel SYN-0149:\n")
    out.append("> *Kết quả Plt là 0 10^9/L, đây là một kết quả rất thấp. Thường, mức Plt bình "
               "thường nằm trong khoảng 150–400 10^9/L.*\n")
    out.append("Layer 2 labelled the platelet count low, the model said low, and the second "
               "sentence merely quotes the interval. The check reports contradictory wording "
               "all the same. Scanning the 206 flagged sentences in the baseline log for this "
               "shape identifies 50 of them (24.3%) as candidates for the same mistake. The "
               "figure comes from a pattern scan and not from annotation, so it is an "
               "indication of magnitude rather than a precision estimate.\n")
    out.append("We left the behaviour in place for this paper, because changing the validator "
               "after seeing the results would invalidate the comparison between "
               "configurations that were already scored with it. The direction of the bias is "
               "worth stating: a validator that over-reports contradictions rejects outputs "
               "that were in fact acceptable, which inflates the fallback rate and therefore "
               "understates how much usable text the model produced. It does not inflate the "
               "pass rate. Establishing precision and recall against human-annotated "
               "statements, and then correcting the masking rule, is the first item of future "
               "work on Layer 4.\n")


def phu_luc_c(out):
    f = ROOT / "results" / "vi_du_loi.json"
    if not f.exists():
        return
    vd = json.load(open(f, encoding="utf-8"))
    out.append("## Appendix C — Worked examples, one per error class\n")
    out.append("Every example below is taken from the stored run logs in `results/`; none is "
               "constructed for illustration. The replacement output in each case is the "
               "fixed template of Layer 4, which states value, reference interval and label.\n")
    out.append("| Error class | Panel | Rule label | Analyte | What the model produced | Why Layer 4 rejected it |")
    out.append("|---|---|---|---|---|---|")
    for lop, d in vd.items():
        cau = (d.get("cau_mo_hinh") or d.get("ket") or "").replace("|", "/")
        if len(cau) > 190:
            cau = cau[:187] + "..."
        v = d["vi_pham"]
        if lop == "status_mismatch":
            ly = f"status `{v.get('got')}` where Layer 2 assigned `{v.get('expected')}`"
        elif lop == "contradictory_wording":
            ly = f"prose reads as `{v.get('found_as')}` where Layer 2 assigned `{v.get('state')}`"
        elif lop in ("forbidden_term", "false_reassurance"):
            ly = f"matched `{v.get('pattern')}`"
        elif lop == "hallucinated_analyte":
            ly = "analyte not present in the input panel"
        else:
            ly = "analyte present in the input but absent from the output"
        out.append(f"| {lop} | {d['panel_id']} | {NHAN_VI.get(d['nhan_phieu'], d['nhan_phieu'])} "
                   f"| {d['ma']} | {cau} | {ly} |")
    out.append("")


def main():
    out = ["# Supplementary appendices — HI26-0013\n",
           "Paper: *A Rule-Constrained Large Language Model Pipeline for Rule-Consistent "
           "Explanation of Vietnamese Complete Blood Count Results*\n",
           "These appendices answer Reviewer 1's points 3 (reproducibility of the benchmark), "
           "7 (specification of the validator) and 10 (qualitative error analysis). They are "
           "generated from the running code by `src/dung_phu_luc.py`, so they cannot drift "
           "from the implementation.\n"]
    phu_luc_a(out)
    phu_luc_b(out)
    phu_luc_c(out)
    RA.write_text("\n".join(out), encoding="utf-8")
    print("Đã ghi:", RA, f"({len('\n'.join(out))} ký tự)")


if __name__ == "__main__":
    main()
